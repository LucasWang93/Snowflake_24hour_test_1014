@pytest.fixture(scope="module")
def live(catalog):
    if os.environ.get("RUN_PHASE2_LIVE") != "1":
        pytest.skip(
            "Actual Phase 2 Cortex/Snowflake tests disabled; RUN_PHASE2_LIVE=1 is opt-in, not PASS"
        )
    backend = SnowflakeBackend(catalog, "llama3.3-70b")
    agent = CensusAgent(catalog, backend)
    path = Path(os.environ.get("PHASE2_EVIDENCE", str(ROOT / "docs/phase2_live_results.json")))
    evidence = {
        "started_at_utc": datetime.now(timezone.utc).isoformat(),
        "cases": [],
        "references": [],
    }

    def save():
        path.write_text(json.dumps(evidence, indent=2, default=str) + "\n")

    def ask(question, state=None, case=""):
        response = agent.ask(question, state)
        evidence["cases"].append(
            {"case": case, "question": question, "response": response.as_dict()}
        )
        evidence["permissions"] = backend.audit
        save()
        print(
            f"LIVE {case}: {response.status}; {response.latency_seconds}s; field={response.metric['id'] if response.metric else None}",
            flush=True,
        )
        return response

    def reference(table, column, scope, year=2020):
        # Independently specified golden field; never generated by the agent/LLM.
        assert (table, column) in catalog.physical
        prefix = ".".join(
            quote_identifier(v) for v in (catalog.data["database"], catalog.data["schema"])
        )
        qualified = prefix + "." + quote_identifier(table)
        col = quote_identifier(column)
        if len(scope) == 12:
            sql = f'SELECT {col} FROM {qualified} WHERE "CENSUS_BLOCK_GROUP" = %s LIMIT 2'
            params = (scope,)
        else:
            sql = f'SELECT SUM({col}) FROM {qualified} WHERE "CENSUS_BLOCK_GROUP" LIKE %s'
            params = (scope + "%",)
        backend.connect(Deadline(budget=20))
        actual = backend._run(sql, params, 15, 2)
        evidence["references"].append({"sql": sql, "params": params, "year": year, **actual})
        save()
        assert len(actual["rows"]) == 1 and actual["rows"][0][0] is not None
        return float(actual["rows"][0][0])

    yield ask, reference, backend
    evidence["cleanup"] = backend.suspend()
    backend.close()
    evidence["finished_at_utc"] = datetime.now(timezone.utc).isoformat()
    save()
    assert evidence["cleanup"]["confirmed_suspended"]


def verify(response, table, columns, value):
    assert response.status == "answered", response.as_dict()
    assert response.metric["table"] == table and response.metric["column"] in columns
    assert response.results[0]["value"] == pytest.approx(value, rel=1e-12, abs=1e-9)
    assert response.latency_seconds < 60
    assert response.sql and all(q.get("query_id") for q in response.sql)
    assert response.model_calls and all(m.get("query_id") for m in response.model_calls)
    assert "universe:" in response.answer and "Year/release:" in response.answer
    assert "statistical source:" in response.answer


